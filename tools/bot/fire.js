const mineflayer = require('mineflayer')
const rcon = require('./rcon')
const sleep = ms => new Promise(r => setTimeout(r, ms))
const bot = mineflayer.createBot({ host: '127.0.0.1', port: 25565, username: 'Gunner', version: '1.21.11', auth: 'offline' })
bot._client.on('add_resource_pack', (p) => { for (const r of [3, 4, 0]) bot._client.write('resource_pack_receive', { uuid: p.uuid, result: r }) })
let shots = 0
bot.on('soundEffectHeard', (s) => { if (String(s).includes('gun.')) { shots++; console.log('sound', s) } })
bot.on('actionBar', m => console.log('bar', m.toString()))
bot.once('spawn', async () => {
  await sleep(2500)
  await rcon('cv give Gunner m4c')
  await rcon('cv give Gunner ammo_556_m855 60')
  await rcon('execute as Gunner at @s run tp @s 11.5 65 -7.5 180 0')
  await sleep(1000)
  const slot = bot.inventory.slots.findIndex((s, i) => i >= 36 && i <= 44 && s && JSON.stringify(s.components || '').includes('m4c'))
  bot.setQuickBarSlot(slot - 36)
  await sleep(500)
  console.log('before', bot.entity.position.toString(), bot.entity.yaw, bot.entity.pitch)
  bot.activateItem(); await sleep(1000); bot.deactivateItem()
  console.log('after', bot.entity.position.toString(), bot.entity.yaw, bot.entity.pitch)
  await sleep(500)
  console.log('shots heard', shots)
  bot.quit()
})
bot.on('end', () => process.exit(0))
